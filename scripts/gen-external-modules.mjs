#!/usr/bin/env node
/**
 * 外部模块装配器：发现 `modules/*` → 生成两处注册表 + Prisma 符号链接
 * + 登记 tenant-models / tenant-guard / 静态 module-manifest。
 *
 * 外部模块是**独立 workspace 包**（各自有 package.json），只许依赖 `@be-water/module-sdk`
 * （+ `@be-water/ui` + 第三方）。本脚本把它们接进 be-water 的编译期组装链路：
 *
 *   - server：生成 `apps/server/src/external-modules.ts`，导出 `EXTERNAL_SERVER_MODULES`
 *   - client：生成 `apps/client/src/external-modules.ts`，导出 `EXTERNAL_CLIENT_MODULES`
 *   - Prisma：把外部包的 `schema.prisma` 符号链接进 `apps/server/prisma/models/<id>.prisma`
 *     （与内部模块同构，§8.3 单全局迁移历史不变，迁移由消费方本地 `migrate dev` 生成）
 *   - 租户列 / tenant-guard / CI 静态清单：与内部模块同样的四处登记
 *
 * 约定（外部包 package.json 的 `beWater` 字段）：
 *   {
 *     "moduleId": "bookmark",                 // 模块 id，决定注册顺序与导出名
 *     "prismaSchema": "./prisma/schema.prisma", // 可选；无则视为无状态模块
 *     "requires": ["note"]                      // 可选；依赖的其它模块 id
 *   }
 *
 * 导出名按 moduleId 派生（与内部 gen-module 同 convention）：
 *   server/index.ts  → export const <camel(id)>ServerModule: ServerAppModule
 *   client/module.tsx → export const <camel(id)>ClientModule: ClientAppModule
 *
 *   node scripts/gen-external-modules.mjs           # 生成
 *   node scripts/gen-external-modules.mjs --check   # 只校验注册表是否最新，不写
 */
import { execFileSync } from "node:child_process";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  readlinkSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const EXTERNAL_DIR = path.join(ROOT, "modules");
const SERVER_REGISTRY = path.join(
  ROOT,
  "apps",
  "server",
  "src",
  "external-modules.ts",
);
const CLIENT_REGISTRY = path.join(
  ROOT,
  "apps",
  "client",
  "src",
  "external-modules.ts",
);
const PRISMA_MODELS_DIR = path.join(ROOT, "apps", "server", "prisma", "models");
const TENANT_MODELS_JSON = path.join(
  ROOT,
  "eslint-rules",
  "tenant-models.json",
);
const TENANT_GUARD = path.join(
  ROOT,
  "packages",
  "server-kernel",
  "src",
  "lib",
  "tenant-guard.ts",
);
const STATIC_MANIFEST = path.join(
  ROOT,
  "apps",
  "server",
  "scripts",
  "lib",
  "module-manifest.ts",
);
const APP_PACKAGES = [
  path.join(ROOT, "apps", "server", "package.json"),
  path.join(ROOT, "apps", "client", "package.json"),
];

/** 内核 / 基础设施包白名单——这些 @be-water/* 包不是外部模块，不应被清理 */
const INTERNAL_BW_PACKAGES = new Set([
  "@be-water/builtin",
  "@be-water/server-kernel",
  "@be-water/client-kit",
  "@be-water/shared",
  "@be-water/ui",
  "@be-water/server-test",
  "@be-water/client-test",
  "@be-water/module-sdk",
]);

const args = new Set(process.argv.slice(2));
const CHECK_ONLY = args.has("--check");

const camel = (s) => s.replace(/-(\w)/gu, (_, c) => c.toUpperCase());
const read = (p) => readFileSync(p, "utf8");

// ---------------------------------------------------------------- 发现外部模块

function discover() {
  if (!existsSync(EXTERNAL_DIR)) return [];
  const out = [];
  for (const entry of readdirSync(EXTERNAL_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const pkgPath = path.join(EXTERNAL_DIR, entry.name, "package.json");
    if (!existsSync(pkgPath)) continue;
    const pkg = JSON.parse(read(pkgPath));
    const bw = pkg.beWater;
    if (!bw || !bw.moduleId) continue;
    // 目录名必须等于 moduleId——Prisma schema 归属推导、符号链接命名、
    // module-dependency-rules 的扫描路径都依赖此约定。
    if (entry.name !== bw.moduleId) {
      console.error(
        `✗ 外部模块目录名 "${entry.name}" 与 beWater.moduleId "${bw.moduleId}" 不一致——必须相同。`,
      );
      process.exit(1);
    }
    out.push({
      pkgName: pkg.name,
      dirName: entry.name,
      moduleId: bw.moduleId,
      prismaSchema: bw.prismaSchema
        ? path.join(EXTERNAL_DIR, entry.name, bw.prismaSchema)
        : null,
      requires: bw.requires ?? [],
    });
  }
  return out;
}

// ---------------------------------------------------------------- 生成注册表

function renderServerRegistry(modules) {
  const imports = modules
    .map(
      (m) =>
        `import { ${camel(m.moduleId)}ServerModule } from "${m.pkgName}/server/index.js";`,
    )
    .join("\n");
  const body = modules
    .map((m) => `  ${camel(m.moduleId)}ServerModule,`)
    .join("\n");
  return `// GENERATED by \`pnpm gen:external-modules\`. Do not edit.
// 外部模块（modules/*）的 server manifest 聚合。
// 内部模块仍在 enabled-modules.ts 里手写；本文件只管外部。
${imports}

import type { ServerAppModule } from "@be-water/server-kernel/runtime/module-contract.js";

export const EXTERNAL_SERVER_MODULES = [
${body}
] as const satisfies readonly ServerAppModule[];
`;
}

function renderClientRegistry(modules) {
  const imports = modules
    .map(
      (m) =>
        `import { ${camel(m.moduleId)}ClientModule } from "${m.pkgName}/client/module.js";`,
    )
    .join("\n");
  const body = modules
    .map((m) => `  ${camel(m.moduleId)}ClientModule,`)
    .join("\n");
  return `// GENERATED by \`pnpm gen:external-modules\`. Do not edit.
// 外部模块（modules/*）的 client manifest 聚合。
${imports}

import type { ClientAppModule } from "@be-water/client-kit";

export const EXTERNAL_CLIENT_MODULES = [
${body}
] as const satisfies readonly ClientAppModule[];
`;
}

// ---------------------------------------------------------------- Prisma 符号链接 + 租户登记

/** 解析 schema 里的 model 名与是否含 tenant_id 列。 */
function parseModels(schemaPath) {
  const text = read(schemaPath);
  const models = [];
  for (const m of text.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gmu)) {
    const [, name, body] = m;
    models.push({
      name,
      prismaClient: name[0].toLowerCase() + name.slice(1),
      hasTenantId: /^\s*tenant_id\s+/mu.test(body),
    });
  }
  return models;
}

function ensureSymlink(moduleId, targetAbsPath) {
  const linkPath = path.join(PRISMA_MODELS_DIR, `${moduleId}.prisma`);
  const relTarget = path.relative(PRISMA_MODELS_DIR, targetAbsPath);
  if (existsSync(linkPath) || isBrokenLink(linkPath)) {
    // 已存在则校验是符号链接且目标正确；不一致就重建
    if (
      lstatSync(linkPath).isSymbolicLink() &&
      readlinkSync(linkPath) === relTarget
    )
      return;
    unlinkSync(linkPath);
  }
  symlinkSync(relTarget, linkPath);
}

function isBrokenLink(p) {
  try {
    return lstatSync(p).isSymbolicLink() && !existsSync(p);
  } catch {
    return false;
  }
}

function patchTenantModels(models) {
  const map = JSON.parse(read(TENANT_MODELS_JSON));
  let changed = false;
  for (const model of models) {
    if (!model.hasTenantId) continue;
    if (!(model.prismaClient in map)) {
      map[model.prismaClient] = "tenant_id";
      changed = true;
    }
  }
  if (changed)
    writeFileSync(TENANT_MODELS_JSON, `${JSON.stringify(map, null, 2)}\n`);
}

function patchTenantGuard(models) {
  let text = read(TENANT_GUARD);
  let changed = false;
  for (const model of models) {
    if (!model.hasTenantId) continue;
    if (!new RegExp(`^  ${model.name}:`, "mu").test(text)) {
      text = text.replace(
        /(const MODEL_POLICIES: Record<string, ModelPolicy> = \{\n)/u,
        `$1  ${model.name}: { kind: "tenant_id" },\n`,
      );
      changed = true;
    }
  }
  if (changed) writeFileSync(TENANT_GUARD, text);
}

function patchStaticManifest(modules) {
  let text = read(STATIC_MANIFEST);
  let changed = false;
  for (const m of modules) {
    if (text.includes(`id: "${m.moduleId}"`)) continue;
    const requires =
      m.requires.length > 0
        ? `\n    requires: [${m.requires.map((r) => `"${r}"`).join(", ")}],`
        : "";
    const entry = `  {\n    id: "${m.moduleId}",\n    kind: "business",${requires}\n  },\n`;
    text = text.replace(
      /(\n\] as const satisfies readonly ModuleManifestEntry\[\];)/u,
      `\n${entry}$1`.replace(/^\n/u, ""),
    );
    changed = true;
  }
  if (changed) writeFileSync(STATIC_MANIFEST, text);
}

/**
 * 同步 apps/server + apps/client 的 dependencies：
 *   - 缺失的外部模块包 → 加 `"@be-water/<pkg>": "workspace:*"`
 *   - 已删除的外部模块包 → 移除（仅限非内核包且目录已不存在的）
 *
 * pnpm 严格模式不创建幽灵依赖，apps 必须显式声明才能 resolve。
 * 这一步让 `pnpm gen:external-modules && pnpm install` 成为外部模块接入的完整闭环。
 */
function patchAppDependencies(modules) {
  const externalPkgNames = new Set(modules.map((m) => m.pkgName));
  const touched = [];
  for (const appPkgPath of APP_PACKAGES) {
    const pkg = JSON.parse(read(appPkgPath));
    if (!pkg.dependencies) pkg.dependencies = {};
    let changed = false;

    // 1. 补缺失
    for (const name of externalPkgNames) {
      if (!(name in pkg.dependencies)) {
        pkg.dependencies[name] = "workspace:*";
        changed = true;
      }
    }

    // 2. 清已删（仅清 @be-water/* 且非内核且 external-modules 目录已不存在的）
    for (const dep of [...Object.keys(pkg.dependencies)]) {
      if (INTERNAL_BW_PACKAGES.has(dep)) continue;
      if (!dep.startsWith("@be-water/")) continue;
      if (externalPkgNames.has(dep)) continue;
      const shortName = dep.replace(/^@be-water\//u, "");
      if (!existsSync(path.join(EXTERNAL_DIR, shortName))) {
        delete pkg.dependencies[dep];
        changed = true;
      }
    }

    if (changed) {
      const sorted = {};
      for (const key of Object.keys(pkg.dependencies).sort())
        sorted[key] = pkg.dependencies[key];
      pkg.dependencies = sorted;
      writeFileSync(appPkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
      touched.push(appPkgPath);
    }
  }
  return touched;
}

// ---------------------------------------------------------------- 主流程

const modules = discover();

if (modules.length === 0) {
  const empty = `// GENERATED by \`pnpm gen:external-modules\`. Do not edit.
// 暂无外部模块。添加 modules/<pkg>/ 后重跑生成。
import type { ServerAppModule } from "@be-water/server-kernel/runtime/module-contract.js";
export const EXTERNAL_SERVER_MODULES = [] as const satisfies readonly ServerAppModule[];
`;
  const emptyClient = `// GENERATED by \`pnpm gen:external-modules\`. Do not edit.
import type { ClientAppModule } from "@be-water/client-kit";
export const EXTERNAL_CLIENT_MODULES = [] as const satisfies readonly ClientAppModule[];
`;
  if (!CHECK_ONLY) {
    writeFileSync(SERVER_REGISTRY, empty);
    writeFileSync(CLIENT_REGISTRY, emptyClient);
    // 清理已删除外部模块在 apps/* 里的残留依赖
    const depTouched = patchAppDependencies([]);
    if (depTouched.length) {
      console.log("✓ 已清理 apps 中残留的外部模块依赖（需重跑 pnpm install）");
    }
    console.log("✓ 无外部模块，已写入空注册表");
  } else {
    console.log("✓ 无外部模块");
  }
  process.exit(0);
}

const serverOut = renderServerRegistry(modules);
const clientOut = renderClientRegistry(modules);

if (CHECK_ONLY) {
  const stale = [];
  if (read(SERVER_REGISTRY) !== serverOut)
    stale.push("apps/server/src/external-modules.ts");
  if (read(CLIENT_REGISTRY) !== clientOut)
    stale.push("apps/client/src/external-modules.ts");
  if (stale.length) {
    console.error(
      `✗ 外部模块注册表过期，请跑 \`pnpm gen:external-modules\`：\n  ${stale.join("\n  ")}`,
    );
    process.exit(1);
  }
  console.log(`✓ ${modules.length} 个外部模块注册表已最新`);
  process.exit(0);
}

writeFileSync(SERVER_REGISTRY, serverOut);
writeFileSync(CLIENT_REGISTRY, clientOut);

const touched = [SERVER_REGISTRY, CLIENT_REGISTRY];
for (const m of modules) {
  if (!m.prismaSchema || !existsSync(m.prismaSchema)) continue;
  ensureSymlink(m.moduleId, m.prismaSchema);
  const models = parseModels(m.prismaSchema);
  patchTenantModels(models);
  patchTenantGuard(models);
  touched.push(TENANT_MODELS_JSON, TENANT_GUARD);
}

patchStaticManifest(modules);
touched.push(STATIC_MANIFEST);

// 同步 apps/* 的 dependencies（补缺失 / 清已删）
const depTouched = patchAppDependencies(modules);
touched.push(...depTouched);

try {
  execFileSync("npx", ["prettier", "--write", ...touched], {
    cwd: ROOT,
    stdio: "pipe",
  });
} catch (err) {
  console.warn(
    `⚠ prettier 未完全通过：${err.stdout?.toString() ?? err.message}`,
  );
}

console.log(`✓ 已装配 ${modules.length} 个外部模块：`);
for (const m of modules) {
  console.log(
    `  • ${m.moduleId} (${m.pkgName})${m.prismaSchema ? " +prisma" : ""}`,
  );
}
if (depTouched.length) {
  console.log("⚠ apps 依赖已更新，请跑 `pnpm install` 让 pnpm 链接新包");
}
console.log(
  "  接下来：pnpm install && pnpm --filter server exec prisma migrate dev --name <external_schema>",
);
